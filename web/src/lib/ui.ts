/**
 * Чому комора порожня. Причину вирішує РЕЖИМ, а не самі числа (#363).
 *
 * У режимі чеків порожньо завжди означає «поріг циклу ще не набрано», і
 * речення про три покупки в різні дні там правда. У режимі «веду сам» циклів
 * не читають узагалі -- які рядки існують, вирішує гість (#109), -- тож те
 * саме речення стверджує про його ЧЕКИ те, чого ніхто не питав, а обіцянка
 * «далі комора почне заповнюватись сама» просто не збудеться. Той самий клас,
 * що наше «поки не вміємо», прочитане як факт про район гостя (#101).
 *
 * Дім у правила ОДИН, бо екранів двоє. Поки рішення про режим жило локальною
 * функцією всередині `Pantry.svelte`, дороги до нього не мав НІХТО, крім тієї
 * комори: старт малював текст про пороги в обох режимах, і виглядало це як
 * робочий продукт (той самий клас, що `marks`, які не доїжджали до порту,
 * #144). Тому розвилка стоїть у входу, а не в кожного читача.
 */
