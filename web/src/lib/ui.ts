/**
 * Звести написане до порівнюваного -- ОДИН дім на пошук по коморі і на
 * підказки вікна (#158).
 *
 * АПОСТРОФ ТУТ НЕ ПРИКРАСА, А ЗБІГ. У чеках «Сільпо» і на клавіатурі гостя
 * живуть два різні символи -- ASCII `'` і типографський U+2019, -- і без
 * зведення «м'ясо» гостя не збігається з «М'ясом» з чека, тобто пул своїх
 * видів мовчки не знаходить те, що в ньому лежить, і близнюк заводиться саме
 * там, де підказка й ставилась.
 *
 * ПИСАНИЙ КОДОМ СИМВОЛУ НАВМИСНО: тут стояло `replaceAll("'", "'")`, де
 * ОБИДВА операнди -- ASCII 0x27, тобто заміна себе на себе. Правило написали,
 * воно жодного разу не спрацювало і виглядало зробленим (той самий клас, що
 * селекторна політика петлі в `api/app.py`). Найімовірніша причина -- прохід
 * `text_lint --fix` по літералу: типографський символ у ньому не відрізнити
 * від друкарської помилки, тому далі він живе екранованим.
 */
export function plainKind(text: string): string {
  return text.toLowerCase().replaceAll('\u2019', "'").trim()
}

/** Що показати під полем вводу і ЧОМУ саме це. */
export type AddHints = {
  chips: string[]
  /** Підпис над чипсами. Порожнього ряду без причини тут не буває (#38).
   *
   * РІЗНИЦЮ НЕСЕ ТЕКСТ, А НЕ КОЛІР: `--muted` і `--faint` у світлій темі
   * збігаються значення в значення, тож пофарбований підпис розрізняв би
   * стани рівно в одній темі з двох -- тобто був би контролом, який нічого
   * не міняє (#132), і виглядав би зробленим (#100). */
  note: string
}

/**
 * ПІДКАЗКИ ВІКНА -- ЦЕ НЕ ШВИДКІСТЬ НАБОРУ, А ТЕ, ЩО БЛИЗНЮК НЕ ЗАВОДИТЬСЯ
 * (#188, #85). Це і є критерій успіху задачі, і саме він вирішує форму.
 *
 * Пул -- ВИКЛЮЧНО свої види гостя (рядки комори і те, що чеки ведуть поза
 * нею), ніколи не каталог: перелік мовчки робить несказанним те, чого в ньому
 * немає (#101), а комора -- єдиний екран, який працює без «Сільпо» взагалі.
 * Поле при цьому лишається ВІЛЬНИМ текстом: підказка тільки заповнює його,
 * тож голос і список ділять одне поле і один стан.
 *
 * Збіг -- ВХОДЖЕННЯ, а не схожість. Порога схожості тут немає СВІДОМО: він
 * був би числом з голови (#203), а зміряти його нема на чому -- скільки
 * дописаних майже дослівно повторюють наявний вид, ще не рахували (#155).
 * Входження помиляється в безпечний бік: воно мовчить там, де не певне, а не
 * підсовує чужий вид під набране слово.
 *
 * Станів ТРИ, і в кожного свій підпис, бо поради в них різні (#38). Мовчазний
 * порожній ряд нерозрізненний з «підказок не буває», а чотири слова з нашого
 * коду, показані так само, як його власні види, -- це вже обіцянка, якої
 * продукт не давав (#132, #189): гість тисне «мед» і думає, що ми знаємо, що
 * він бере мед.
 *
 * ВХОДІВ ДВА, І ЦЕ НЕ ДУБЛЬ. `pool` -- усі свої види, ним лише ЗБІГАЄТЬСЯ
 * набране; `untracked` -- ті, яких комора ще не веде, і саме вони стоять
 * прикладами на порожньому полі. Один список на обидві роботи брехав би
 * підписом: рядок комори, показаний під «комора їх ще не веде», -- це
 * твердження, зворотне до правди, і помітити його можна лише на теплому
 * акаунті.
 */
export function addHints(pool: string[], untracked: string[], typed: string): AddHints {
  const needle = plainKind(typed)
  if (needle !== '') {
    const hit = pool.filter((kind) => plainKind(kind).includes(needle))
    if (hit.length > 0) {
      return {
        chips: hit.slice(0, PANTRY_CHIPS),
        note: 'таке в тебе вже є — візьми це слово, щоб у коморі не завелось два рядки одного виду',
      }
    }
    return { chips: [], note: 'серед твоїх видів такого ще немає — додам новим' }
  }
  if (untracked.length > 0) {
    return {
      chips: untracked.slice(0, PANTRY_CHIPS),
      note: 'з твоїх покупок — комора їх ще не веде',
    }
  }
  return {
    chips: PANTRY_SUGGESTIONS,
    note: 'своїх видів поки не видно — ось приклади ФОРМИ: вид, а не марка',
  }
}

