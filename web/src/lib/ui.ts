/**
 * Скільки коштував ЦЕЙ ВХІД — один рядок на два трейси (прохання власника
 * 08.09: «пиши суму, витрачену за сесію, і кількість токенів усього — комора
 * плюс замовлення»).
 *
 * ДІМ ОДИН, БО ЧИТАЧІВ ДВОЄ. Рядок стоїть і в «звідки це» комори, і в
 * журналі кошика; написаний двічі, він розійшовся б першою ж правкою, а
 * побачити це можна було б лише поклавши два екрани поруч (#158).
 *
 * `null` тут означає рівно одне — сказати нема чого: або лічильник не
 * відповів (`toll === null`), або прогонів від входу ще не було. Нуль
 * прогонів окремим рядком був би числом без осі: гість щойно зайшов.
 */
export function tollNote(toll: Toll | null, label = 'цей вхід'): string | null {
  if (toll === null || toll.runs === 0) return null
  const runs = plural(toll.runs, { one: 'прогін', few: 'прогони', many: 'прогонів' })
  const money = toll.usd === null ? 'ціни моделі не знаємо' : usdFine(toll.usd)
  const gap =
    toll.usd !== null && toll.unpriced > 0
      ? ` (без ${plural(toll.unpriced, { one: 'прогону', few: 'прогонів', many: 'прогонів' })} без прайсу)`
      : ''
  const whose =
    toll.guestUsd === null
      ? ''
      : toll.guestUsd === toll.usd
        ? ' · ключем гостя, поза добовою стелею'
        : ` · з них ${usdFine(toll.guestUsd)} ключем гостя, поза добовою стелею`
  return `${label}: ${runs} · ${money}${gap}${whose} · ${toll.tokensIn} → ${toll.tokensOut} ток.`
}


/**
 * Скільки з'їв ЦЕЙ ЗАБІГ -- від відкриття вкладки до оновлення сторінки
 * (прохання власника 08.09: «хоч загальну... в цьому забігу, доки сторінку
 * не оновив»).

 * РІЗНИЦЯ, А НЕ СВІЙ ЛІЧИЛЬНИК, і це головне рішення тут. Своє накопичення
 * довелося б дописувати в КОЖЕН шлях, який ходить у модель -- комора, петля,
 * збірка, добір, правки, бар, -- і перший забутий шлях мовчки занизив би
 * число (клас #144). Сервер уже рахує все це під ключем входу; знімок на
 * старті плюс віднімання дає точну відповідь на іншій осі і не вміє
 * розійтися з нею за побудовою.
 *
 * `null` -- знімка ще немає (лічильник мовчав на старті) або від тоді нічого
 * не витрачено. Нуль прогонів окремим рядком був би числом без осі.
 */
export function tollSince(now: Toll | null, base: Toll | null): Toll | null {
  if (now === null) return null
  const was = base ?? { runs: 0, usd: 0, unpriced: 0, tokensIn: 0, tokensOut: 0, guestUsd: 0 }
  const runs = now.runs - was.runs
  if (runs <= 0) return null
  const unpriced = now.unpriced - was.unpriced
  return {
    runs,
    usd: now.usd === null ? null : now.usd - (was.usd ?? 0),
    unpriced,
    tokensIn: now.tokensIn - was.tokensIn,
    tokensOut: now.tokensOut - was.tokensOut,
    guestUsd: now.guestUsd === null ? null : now.guestUsd - (was.guestUsd ?? 0),
  }
}