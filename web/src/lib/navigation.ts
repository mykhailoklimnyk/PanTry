/**
 * Екрани застосунку. Роутера немає навмисно: демо — один вертикальний потік,
 * і адресний рядок у ньому нічого не додає, зате додає стани, які треба
 * відновлювати перед записом відео.
 */
export type Screen =
  | 'start'
  | 'running'
  | 'cart'
  | 'trace'
  | 'swaps'
  | 'pantry'
  | 'bar'
  /** Стан оформленого замовлення (#50). Не вкладка кошика: він тут уже
   *  переданий, і повертатись до перевірки складу нема куди. */
  | 'order'
  /** Згода на доступ до акаунта «Сільпо». Не сторінка меню: це частина
   *  продукту, і показується вона ДО редіректу на логін. */
  | 'connect'
  | DocId

/**
 * Сторінки з бургер-меню. Це не частина продукту для гостя — це відповіді
 * журі на питання, які інакше доводиться проговорювати на камеру: чим
 * перевірено код, що готове, і чому ми свідомо не робимо частину речей.
 */
export type DocId = 'quality' | 'stack' | 'ideas'

const DOC_IDS: DocId[] = ['quality', 'stack', 'ideas']

export function isDoc(screen: Screen): screen is DocId {
  return (DOC_IDS as string[]).includes(screen)
}

/**
 * Вкладки над списком: рух між ними — убік, а не вглиб.
 *
 * Вони існують лише тоді, коли є кошик: це навігація ЙОГО контексту
 * (перевірив кошик → подивився, що вдома → чим доповнити бар).
 */
export const TABS: Screen[] = ['cart', 'pantry', 'bar']

/**
 * Екрани, з яких шлях починається: у них «назад» не веде нікуди.
 *
 * Старт — початок продукту, кошик — початок роботи з зібраним кошиком. Тому
 * прихід на них обнуляє слід: інакше після десяти збірок «назад» водив би
 * гостя по кошиках, яких уже немає.
 */
const ROOTS: Screen[] = ['start', 'cart']

/** Скільки кроків тримаємо. Глибший слід — це вже історія браузера. */
const MAX_TRAIL = 8

/**
 * Слід «звідки прийшли» після переходу `from` → `to`.
 *
 * ОДИН механізм на всі екрани — і це головне тут. Раніше кожен екран мав
 * свій прапорець («куди повернутись зі сторінки меню», «куди повернутись з
 * комори»), і два з них ділили одну змінну: шлях акаунт → якість → назад
 * приводив назад в акаунт, а друге «назад» уже нікуди не вело — змінну
 * перезаписав перший перехід (#92, живий тест 21.08).
 *
 * `running` у слід не потрапляє: це не екран, а очікування, і повертатись
 * на нього нема куди.
 */
export function pushed(trail: Screen[], from: Screen, to: Screen): Screen[] {
  if (from === to || to === 'running') return trail
  if (ROOTS.includes(to)) return []
  if (from === 'running') return trail
  if (TABS.includes(from) && TABS.includes(to) && from !== 'cart') return trail
  return [...trail, from].slice(-MAX_TRAIL)
}

/** Куди веде «назад» і що лишається від сліду. Порожній слід — на початок. */
export function popped(trail: Screen[]): { to: Screen; trail: Screen[] } {
  const to = trail.at(-1) ?? 'start'
  return { to, trail: trail.slice(0, -1) }
}

/**
 * Підпис кнопки «назад» — за ЦІЛЛЮ, а не за поточним екраном.
 *
 * Кнопка без підпису на вузькому екрані виглядає однаково скрізь, а веде
 * щоразу в інше місце; підпис читає скрінрідер і бачить `title`.
 */
export function backLabel(to: Screen): string {
  if (to === 'cart') return 'До кошика'
  if (to === 'pantry') return 'До комори'
  if (to === 'bar') return 'До бару'
  if (to === 'order') return 'До замовлення'
  if (to === 'connect') return 'До акаунта'
  return 'До покупок'
}

/**
 * Чи показувати вкладки. Вони належать контексту КОШИКА.
 *
 * Комора, відкрита зі старту, лишала гостя у вкладках зібраного кошика,
 * хоча він туди не просився (#92). Вкладки — це навігація всередині
 * перевірки кошика, і поза нею їх бути не має.
 */
export function inTabs(screen: Screen, trail: Screen[]): boolean {
  return screen === 'cart' || (TABS.includes(screen) && trail.at(-1) === 'cart')
}
