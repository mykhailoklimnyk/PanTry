export interface SwapOption {
  externalProductId: string
  name: string
  price: number
  /** Фасовка з картки: «0,5 л», «100г». З назви не виводиться (#39). */
  ratio: string | null
  /**
   * Чи ціна стоїть за КІЛОГРАМ, а не за штуку (#78, #242).
   *
   * Живий тест 01.09: у переліку «обрано з 21» поруч стояли «Ковбаса
   * Альпійська 159 ₴» (палиця 330 г) і «Ковбаса Преміум 1 399 ₴» (кілограм),
   * обидві голим числом. Власник прочитав це як «агент узяв найдорожче» --
   * хоч у кошик поїхала нарізка за 119 ₴. Тобто екран, який має ПОЯСНЮВАТИ
   * вибір, робив його підозрілим.
   *
   * Рахує це сервер, бо правило живе там (`core/packaging.is_sold_by_weight`)
   * і `weighted` у чужій картці бреше: у нектарина воно `false` при
   * `ratio: "кг"`. Другий дім цього правила на екрані розійшовся б мовчки.
   */
  byWeight: boolean
  /**
   * Залишок у філії. None — API його не назвав, і вигадувати нічого.
   *
   * Число, а не `int`: у вагового товару залишок дробовий — 2,5 означає два
   * з половиною кілограми. `int` тут коштував 500-ю на живому проді (20.08):
   * з появою кандидатів у кожному рядку (#43) один ваговий кандидат у видачі
   * валив ЦІЛУ збірку, і падало воно на валідації, тобто мовчки для логів.
   */
  stock: number | null
  available: boolean
  imageUrl: string | null
  /**
   * Картка товару на сайті «Сільпо» -- готовим посиланням, а не слагом.
   *
   * Рішення «немає слага -- немає посилання» ухвалюється тут один раз
   * (`core/links.product_url`), а не на екрані: слаг є не в кожній чужій
   * відповіді, і зібране з нього на фронті посилання вело б на голий
   * `/product/`. Та сама причина, з якої поруч їде готовий `image_url`, а
   * не ідентифікатор картинки.
   */
  cardUrl: string | null
  /**
   * Чи це ТОЙ САМИЙ ВИД, що й рядок. `null` означає «не довели», а не «ні».
   *
   * Три стани, бо доказів рівно два і обидва однобічні: товар лежить у
   * переліку вузла дерева (доводить «так») або назва починається зі слова
   * рядка (теж доводить «так»). Спростувати вид не вміє жоден, тому `false`
   * ставиться лише коли провалились ОБИДВА, і лише за живого переліку: без
   * нього доказів немає взагалі, а не «немає збігу». Живий тест 20.08: до
   * рулета за словом «Мівіна» пропонувалась вермішель швидкого
   * приготування (#80).
   */
  sameKind: boolean | null
  /**
   * Назва виду, з яким звіряли: «Вода мінеральна». Без неї твердження
   * «інший вид» нічим перевірити — гість не бачить осі, на якій воно
   * вимірюється, а помилковий вузол лишається невидимим.
   */
  kind: string | null
  /**
   * Чи каже НАЗВА, що товар нарізаний. Форма видима саме тут, бо полиця
   * перемкнути її не вміє: нарізка — частина ідентичності SKU, і вибір
   * форми — це вибір іншого товару з переліку виду (#102).
   */
  sliced: boolean
}

