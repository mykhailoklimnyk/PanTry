export interface TraceStep {
  /**
   * ВИД кроку («step-refill»), а не сам крок: у трейсі він повторюється.
   *
   * Добір, правка рядка і погодження замін продовжують трейс плану
   * (`trace.steps = list(plan.basket.trace)`), тож два добори поспіль дають
   * два кроки з цим самим іменем. Ключувати ним список не можна -- дубль
   * ключа вбиває весь список, і живий тест 03.09 показав ціну: екран трейсу
   * не відкривався, а разом з ним зникали вкладки кошика (#302).
   */
  id: string
  /**
   * Номер кроку в трейсі, з одиниці. Унікальний за побудовою (`Tracer.add`
   * бере довжину вже накопиченого), тому ключем списку на екрані є саме він.
   */
  seq: number
  tool: string
  /** Уже редаговані — ADR-03. Сирі аргументи на фронт не виходять ніколи. */
  args: Record<string, unknown>
  /**
   * Скільки крок ішов. `None` — його НІХТО не міряв.
   *
   * До 02.09 поле було обов'язковим `int`, і незаміряний крок їхав з нулем за
   * замовчуванням: екран малював йому «<1 мс» поруч зі справжніми 169 мс
   * сусіда, і одне число означало три різні речі — крок не робив нічого, крок
   * ходив у базу без таймера, крок ніхто не міряв (#279). Нуль тепер означає
   * рівно одне — заміряний нуль, тобто швидше за мілісекунду (той самий клас,
   * що з нулем у грошах, #76).
   */
  durationMs: number | null
  /**
   * Скільки разів ЦЕЙ крок питав модель. `None` -- не міряли (крок коду,
   * або лічильника в прогоні немає), і це не те саме, що нуль: нуль означає
   * «крок ходив у модель нуль разів, усе взялось із кешу» (#5).
   *
   * Питання власника 08.09 по живому трейсу: «глузд не іде в 2 потоки?».
   * Кроки `pantry.rhythm`, `pantry.keeps` і `pantry.aisle` дістають ОДИН і
   * той самий перелік зі 101 мітки, а йдуть 19,0 / 6,4 / 5,9 с -- і з самого
   * часу не видно, це різні пачки чи різна довжина відповіді. Час без токенів
   * відповідає на питання, якого не ставили.
   */
  calls: number | null
  tokensIn: number | null
  /**
   * Токени ЦЬОГО кроку. Разом із `calls` вони й розводять дві причини
   * повільності: багато викликів проти довгої відповіді.
   */
  tokensOut: number | null
  resultSummary: string
  decision: string | null
  /** Ярлик наслідку рішення: «вигода 18 ₴», «мінус 2 позиції», «ризик». */
  tag: string | null
  /** Чим фарбувати ярлик. Колір не єдиний носій — текст каже те саме словами. */
  tagTone: 'good' | 'warn' | 'muted'
  externalProductId: string | null
  /**
   * Чим ПИТАЛИ модель: ім'я@хеш системного промпта (#295, `agent/prompts.py`).
   *
   * `None` — крок у модель не ходив; це більшість кроків, і мовчання тут
   * законне. Складений промпт називає свої частини (`pick[head@ab12cd34,
   * tail@…,skill.pack@…]`), бо позиція правила важить не менше за його текст
   * (#200), а цілий хеш не сказав би, чим саме цей кошик відрізняється від
   * сусіднього.
   */
  prompt: string | null
  /**
   * Питання гостю, на яке збірка ЧЕКАЄ просто зараз (#285). None — крок
   * нічого не питає, і таких переважна більшість.
   */
  question: TraceQuestion | null
}

