/**
 * Цінова вилка авто-заміни — словами й грошима гостя (#90).
 *
 * Живий тест 20.08: «заміна ±10% взагалі не ясно як працює». Відсоток не
 * відповідає ні на «від чого», ні на «до чи після знижки», ні на «що буде,
 * якщо не влізе нічого» — а вирішує гість саме це: вмикати стояче
 * погодження замін на весь кошик.
 *
 * Правило живе тут одне на весь фронт навмисно: перемикач стоїть на двох
 * екранах, і два його пояснення розійшлися б мовчки. Самі МЕЖІ рахує
 * бекенд (`core.mandate.price_fork`) і віддає полем рядка: гість мусить
 * бачити ті самі числа, які прочитає збирач.
 */
import { AUTO_SWAP_CAP_UAH } from './facts'
import { amount, uah } from './format'
import type { PriceFork } from './types'

/**
 * «від 64,79 до 79,19 ₴», «від 647 до 791 ₴/кг» — те, що поїде збирачу.
 *
 * КОПІЙКИ ТУТ НЕ ШУМ, і саме тому не `uahRound`. Живий тест 05.09: гість
 * увімкнув ±10% і побачив на картці числа, які тими десятьма відсотками не
 * є. Половину різниці робило округлення самої вилки (лікується в
 * `core/mandate`), другу — округлення НА ЕКРАНІ: «зараз 5 ₴» під ціною 5,49
 * і «зараз 10 ₴» під 9,50 роблять з чесної вилки видиму брехню. Цілі гривні
 * друкуються без хвоста нулів (`amount`), тож дорогий рядок читається як
 * читався.
 */
export function forkRange(fork: PriceFork): string {
  return `від ${amount(fork.low, '')} до ${amount(fork.high, '₴')}${fork.per ? `/${fork.per}` : ''}`
}

/**
 * «зараз 34,90 ₴», «зараз 719,00 ₴/кг» — ціна, ВІД ЯКОЇ рахується вилка.
 *
 * `uah`, а не `amount`: це ЦІНА рядка, і копійки в ній не знімаються навіть
 * нульові — «34,9 ₴» на цінник не схоже, а всі інші ціни в продукті стоять
 * з двома знаками. Межі вилки навпаки друкує `amount`: там нулі знімає і
 * бекенд (`core.mandate.money`), а розійтися їм тут нема на чому (#90).
 */
export function forkBasis(price: number, fork: PriceFork): string {
  return `зараз ${uah(price)}${fork.per ? `/${fork.per}` : ''}`
}

/**
 * Що обіцяє стояче погодження заміни -- і чого воно НЕ обіцяє.
 *
 * ВІДСОТКА ТУТ БІЛЬШЕ НЕМАЄ (рішення власника 05.09). «±10%» відповідало на
 * питання, якого гість не ставив, і не відповідало на те, яке ставив: він
 * вирішує не про десяту частину, а про гроші й про те, чи згоден він на цю
 * заміну взагалі. Там, де ціна відрізняється, слово має сказати ВІН -- на
 * екрані погодження, де стоять справжні числа рядка, -- і тоді питання
 * знімається з нас.
 *
 * Знижки кошика тут не дрібниця: підписка, купони й промо рахуються на
 * рівні КОШИКА і до запису не відомі нікому (#40), а мандат читає людина
 * біля полиці, у якої перед очима цінник, а не наш кошик.
 *
 * Стеля в гривнях лишається названою, бо на першому екрані кошика ще немає
 * і грошей рядка назвати нема з чого. Саме число приїжджає з бекенда через
 * `facts.ts` -- рахує його `core.mandate`, і другий дім розійшовся б
 * мовчки (#158).
 *
 * А СТЕЛЯ ОПИСУЄ ОДНУ З ДВОХ РУК, І ДО 06.09 ЦЬОГО ТУТ НЕ СТОЯЛО (#352).
 * Фраза говорила про весь рядок, а вилка керує ним РІВНО ТОДІ, коли
 * ланцюжок замін не склався: `agent/basket` і `agent/cart` ставлять її в
 * `elif`, тобто `swap_fork` при непорожньому ланцюжку не приходить узагалі.
 * Живий тест 05.09: над списком стояло «не дорожче ніж на 50 ₴», а в
 * ланцюжку печива лежала ланка з різницею 66 ₴ -- гість прочитав це як
 * спростування обіцянки, і мав рацію. Ланцюжок названий ПОІМЕННО і з
 * цінами, тобто межа в ньому -- сама ланка, яку гість бачить і погоджує;
 * стеля обмежує ДОЗВІЛ НА СУМУ для товару, якого ніхто не назвав. Один
 * текст на дві підстави -- те саме, від чого стереже #208.
 */
export function forkNote(): string {
  return (
    'де є список замін — везуть за ним. ' +
    'Де ланцюжка немає — рівноцінна заміна того самого виду і в межах ціни цього рядка, ' +
    `не дорожче ніж на ${AUTO_SWAP_CAP_UAH} ₴; ` +
    'не знайдеться — не привезуть.'
  )
}
