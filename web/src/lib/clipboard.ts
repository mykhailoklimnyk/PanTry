/**
 * Крок у буфер -- ОДНИМ правилом на всі місця, де це пропонується.
 *
 * Копіювання жило в трьох місцях трьома копіями (трейс, панель дебагу,
 * диктофон), і кожне мало власний `try/catch` з власним рішенням, що робити з
 * відмовою. Ціна розходження тут не теоретична: у браузері без дозволу на
 * буфер `writeText` кидає, і копія, яка ковтає це мовчки, показує «скопійовано»
 * над порожнім буфером -- тобто бреше рівно тоді, коли не спрацювала (#38).
 */
export async function copyJson(value: unknown): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(JSON.stringify(value, null, 2))
    return true
  } catch {
    return false
  }
}
