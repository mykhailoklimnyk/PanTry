/**
 * Обґрунтування рядка — картка «Чому саме ці позиції» на екрані трейсу (#72).
 *
 * Правило про те, у кого вона є, живе тут ОДНЕ: його читає екран трейсу (кого
 * показувати) і рядок кошика (чи вести дотик кудись). Два прочитання
 * розійшлися б мовчки, і дотик почав би вести в порожнечу — а зламане
 * посилання зовні не відрізнити від «агент тут нічого не вирішував».
 *
 * Окремого поля-якоря немає навмисно. Воно дорівнювало б артикулу рядка, тобто
 * було б його КОПІЄЮ, а копія протухає окремо від оригіналу. Саме таким полем
 * і був `trace_step_id`: у всіх рядків стояв спільний `step-agent` («вести нема
 * куди»), фронт не читав його жодного разу, а фікстури тим часом малювали в
 * ньому неіснуючу різноманітність — `step-batch`, `step-pantry`, `step-slots`.
 */
import type { CartLine } from './types'

/**
 * Чи має рядок картку обґрунтування.
 *
 * Кандидатів нуль — агент цей рядок не обирав: напій з бару назвав гість, а
 * старі прогони збиралися до того, як відкинуті кандидати взагалі з'явились.
 */
export function hasPick(line: CartLine): boolean {
  return line.consideredTotal > 0
}

/** Id картки в DOM — щоб дотик привів у неї, а не «кудись у трейс». */
export function pickId(externalProductId: string): string {
  return `pick-${externalProductId}`
}

/**
 * Підпис вибору. Один на обидва екрани: «обрано з трьох» у кошику і «вибору не
 * було» в трейсі — це відповідь на одне питання, і дві її редакції розійшлися б
 * так само мовчки, як два фільтри.
 */
export function pickLabel(line: CartLine): string {
  return line.consideredTotal > 1 ? `обрано з ${line.consideredTotal}` : 'вибору не було'
}
