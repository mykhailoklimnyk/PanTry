/**
 * Галочки замін «Сільпо» — і чия рука від них залежить (#49).
 *
 * Ланцюжок має ДВІ руки, і лише одна стоїть під галочкою замовлення:
 *
 * 1. наша — ре-валідація до слота: позиція зникла з полиці раніше за
 *    збирання, і рядок переписує Комора. Дозволу «Сільпо» це не потребує;
 * 2. збирача — мандат у `comment`. Ось він і мертвий при `disapprovedChanges`.
 *
 * Тому екран не має права ні рапортувати «усе погоджено», ні лякати
 * «нічого не спрацює»: обидва варіанти неправда, просто в різні боки.
 *
 * Правило тут одне на весь фронт навмисно: кошик і екран замін кажуть про
 * ту саму галочку, і два її прочитання розійшлися б мовчки.
 */
import type { CartLine, OrderFeedback } from './types'

/**
 * Чи спрацює рука ЗБИРАЧА. `null` — не звіряли (кошик не читався або поле
 * назвало незнайоме слово), і на цьому стані ми не стверджуємо нічого.
 */
export function collectorActs(feedback: OrderFeedback): boolean | null {
  if (feedback.changes === null) return null
  return feedback.changes !== 'disapprovedChanges'
}

/**
 * Чи є що вирішувати перед «Оформити»: ланцюжок на ризиковій позиції або
 * галочка, яка суперечить мандату.
 *
 * Крок показується лише на це. Обов'язковий екран перед головною дією
 * прокликують не читаючи — і тоді він не спрацює саме тоді, коли треба.
 *
 * Після #128 екран показує ВЕСЬ кошик, і питання «а чи не мусить тепер і
 * крок стояти завжди» звірене, а не пропущене. Ні: умова тут про РІШЕННЯ,
 * а екран крім рішень ще й ПІДПИСУЄ. Розширити її до «є хоч один мандат»
 * означало б відкривати крок майже на кожному кошику — мандат стоїть майже
 * скрізь, щойно до слота більше за півдоби (замір 23.08), — тобто зробити
 * рівно те, від чого #49 відмовився, і підпис знову став би кліком. Мандат,
 * поставлений наперед, при цьому не мовчить: кошик показує його блоком з
 * рахунком, і блок цей — кнопка сюди.
 *
 * А ЦІНОВА ВИЛКА -- ТРЕТЯ УМОВА, І ВОНА ПРО ГРОШІ (рішення власника 05.09:
 * «там, де є різниця в ціні, людина має клікнути погоджено -- це
 * обов'язково, вона має сама це погодити, і тоді з нас знімається
 * питання»). Це не те саме, що «є хоч один мандат», і межа проходить по
 * тому, ЧИЄ рішення в мандаті стоїть:
 *
 * — ЛАНЦЮЖОК названий поіменно і з цінами -- гість бачить, що саме поїде,
 *   ще в кошику;
 * — ВИЛКА не називає товару взагалі. Це відкритий дозвіл на суму, і
 *   вигадали її МИ, а не він. Стояче «не питай мене» на першому екрані
 *   ставилось до кошика, якого тоді ще не було.
 *
 * Ціна цієї умови чесна і названа: у гостя з увімкненою авто-заміною крок
 * відкриватиметься майже завжди, тобто саме те, чого #49 уникав. Різниця в
 * тому, що там ішлося про УВАГУ («на що дивитись першим»), а тут про
 * ВІДПОВІДАЛЬНІСТЬ: за суму, яку витратить збирач, підписується гість, і
 * підписатись наосліп він не може -- гроші рядка стоять на його ж картці.
 */
export function swapsToReview(lines: CartLine[], feedback: OrderFeedback): boolean {
  const conflict =
    collectorActs(feedback) === false && lines.some((line) => line.mandate !== null)
  return (
    conflict ||
    lines.some((line) => line.atRisk && line.chain.length > 0) ||
    heldByFork(lines).length > 0
  )
}

/**
 * Рядки, на яких діє ВИЛКА, а не названий ланцюжок (#352).
 *
 * Обидві руки лишають по рядку однакову ознаку -- непорожній `mandate`, --
 * а підстави в них протилежні. ЛАНЦЮЖОК називає товари поіменно і з цінами:
 * гість бачить, що саме поїде, ще в кошику, і в «Погодженні замін»
 * переставляє й прибирає ланки. ВИЛКА товару не називає взагалі -- це
 * відкритий дозвіл на СУМУ, і вигадали його МИ, а не він.
 *
 * Живий тест 05.09 назвав ціну цієї однаковості з іншого боку: над списком
 * стояло «не дорожче ніж на 50 ₴», а в ланцюжку печива лежала ланка з
 * різницею 66 ₴. Картки це вже розводять (`Swaps.svelte`, 06.09), а рахунок
 * у кошику -- ні: одне число під словом «погоджено» описувало обидві руки,
 * хоч погоджене поіменно лише те, що поіменно й назване (#208).
 *
 * Дім один навмисно: те саме питання ставить `swapsToReview` («чи вести на
 * екран погодження») і кошик («яка рука діє на цьому рядку»), а два
 * прочитання розійшлися б мовчки (#158). Ланцюжок тут НЕ дзеркалиться
 * окремою функцією: рядок з мандатом і без вилки буває ще й правилом-текстом
 * («заміни не підбирати», напої), тож «усе, що не вилка» -- не ланцюжок, і
 * функція з такою назвою брехала б на третьому стані.
 */
export function heldByFork(lines: CartLine[]): CartLine[] {
  return lines.filter((line) => line.swapFork !== null)
}
