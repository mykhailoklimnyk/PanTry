import type { CartLine } from './types'

/**
 * Рядок, який просить слова гостя на екрані замін: малий залишок на полиці
 * або рішення без мандата. ОДИН предикат на кошик і на екран замін (11.09):
 * кошик рахував лише `needsApproval`, а після правила «ланцюжок є -- він
 * їде» таких майже не буває, тож кнопка «Чекає твого рішення» зникала, хоч
 * екран замін показував «4 позиції просять рішення» за залишком. Гість
 * бачив лише «погоджено наперед», а вона за задумом відкриває все.
 */
export const asksWord = (line: Pick<CartLine, 'atRisk' | 'needsApproval' | 'decided'>): boolean =>
  line.needsApproval || (line.atRisk && !line.decided)
